export interface AgeParticipationRate {
  group: string;
  listNominal: number;
  voted: number;
  notVoted: number;
  unspecified: number;
  womenVoted: number;
  menVoted: number;
  otherVoted: number;
  classified: number;
  participation: number;
}

export const AGE_DATA: Record<number, AgeParticipationRate[]> = Object.fromEntries(
  Object.entries(AGE_CENSUS_COUNTS).map(([year, rows]) => [
    Number(year),
    rows.map(([group, listNominal, voted, notVoted, unspecified, womenVoted, menVoted, otherVoted]) => ({
      group,
      listNominal,
      voted,
      notVoted,
      unspecified,
      womenVoted,
      menVoted,
      otherVoted,
      classified: voted + notVoted,
      participation: Number(((voted / (voted + notVoted)) * 100).toFixed(1)),
    })),
  ]),
);

export const AGE_ELECTION_YEARS = Object.keys(AGE_DATA).map(Number);
