import fs from 'node:fs/promises';
import path from 'node:path';
import sharp from 'sharp';

// Keep source PNGs for future art edits. Generated WebP files are served by the game.
const root = path.resolve('apps/web/public/assets/juego');
async function walk(dir) {
  const entries = await fs.readdir(dir, { withFileTypes: true });
  return (await Promise.all(entries.map(e => e.isDirectory()
    ? walk(path.join(dir, e.name)) : [path.join(dir, e.name)]))).flat();
}
const files = (await walk(root)).filter(f => f.endsWith('.png'));
let before = 0, after = 0;
// Bound encoder concurrency to avoid exhausting memory on full resolution frames.
let cursor = 0;
await Promise.all(Array.from({ length: 4 }, async () => {
  while (cursor < files.length) {
    const file = files[cursor++];
    const relative = path.relative(root, file).replaceAll('\\', '/');
    const sprite = relative.startsWith('player/') || relative.startsWith('personajes/');
    const output = file.replace(/\.png$/, '.webp');
    await sharp(file).resize({ width: sprite ? 512 : 1920, height: sprite ? 512 : 1920,
      fit: 'inside', withoutEnlargement: true, kernel: 'nearest' })
      .webp({ quality: 88, alphaQuality: 100, effort: 4 }).toFile(output);
    before += (await fs.stat(file)).size;
    after += (await fs.stat(output)).size;
  }
}));
const assetPaths = files.map(file => '/assets/juego/' + path.relative(root, file)
  .replaceAll('\\', '/').replace(/\.png$/, '.webp')).sort();
await fs.mkdir('packages/game/src/features/loading', { recursive: true });
await fs.writeFile('packages/game/src/features/loading/gameAssets.ts',
  '// Generated by scripts/optimize-game-assets.mjs\nexport const GAME_ASSET_PATHS: readonly string[] = ' +
  JSON.stringify(assetPaths, null, 2) + ';\n');
console.log(JSON.stringify({ files: files.length, sourceBytes: before, webpBytes: after,
  reductionPercent: Math.round((1 - after / before) * 100) }));
